from enum import Enum
from typing import Dict, List, Optional
from pydantic import BaseModel, Field

from app.retrievers.models import RetrievedChunk


class ConfidenceLevel(str, Enum):
    """Graded confidence in the generated answer."""
    LOW = "LOW"
    MEDIUM = "MEDIUM"
    HIGH = "HIGH"


class CitationItem(BaseModel):
    """A single traceable source reference attributed to the answer."""
    documentId: str
    filename: str
    pageNumber: int
    chunkId: str
    score: float


class ConfidenceScore(BaseModel):
    """Composite confidence metric derived from retrieval quality signals."""
    level: ConfidenceLevel
    averageSimilarity: float
    chunkCount: int
    contextCoverage: float   # 0.0–1.0: fraction of max_context_chunks used


class PipelineRequest(BaseModel):
    """Input to the RAG pipeline."""
    query: str
    documentId: Optional[str] = None          # Scope retrieval to a single document
    topK: int = Field(default=5, ge=1, le=20)
    scoreThreshold: Optional[float] = None
    conversationHistory: Optional[List[Dict[str, str]]] = None  # Future multi-turn


class PipelineResult(BaseModel):
    """Complete output of a successful RAG pipeline execution."""
    answer: str
    sources: List[CitationItem]
    confidence: ConfidenceScore
    chunks: List[RetrievedChunk]
    executionTimeMs: float
    modelUsed: str
    isFallback: bool = False   # True when no relevant context was found


class LLMResponseCitation(BaseModel):
    """A single source citation generated by the LLM."""
    documentId: str = Field(description="The unique identifier of the source document")
    page: int = Field(description="The page number in the document where the information was found")
    chunkId: str = Field(description="The unique identifier of the chunk")


class LLMStructuredResponse(BaseModel):
    """Structured response output format requested from the LLM."""
    answer: str = Field(description="The final direct answer to the user query based ONLY on the provided context")
    confidence: ConfidenceLevel = Field(description="Grounded confidence level in the answer based on context sufficiency")
    citations: List[LLMResponseCitation] = Field(description="List of traceable source references attributed to the answer")
    reasoning: str = Field(description="Step-by-step reasoning explaining how the answer was derived from the context")
